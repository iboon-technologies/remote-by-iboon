"""
Generates .github/workflows/iboon-build.yml from upstream's flutter-build.yml.

    python res/iboon/make_workflow.py

TeamViewer by iBoon's client only ships Windows x64 (MSI) and Linux x86_64 (.deb), so the
workflow keeps upstream's bridge, Windows-flutter and Linux-flutter jobs,
drops every other platform and architecture, and makes the few changes
branding needs. Generated rather than hand-edited so that, after merging a
new RustDesk release, rerunning this reapplies the same small diff to
upstream's current steps.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / ".github/workflows/flutter-build.yml").read_text(encoding="utf-8")
lines = src.splitlines(keepends=True)

# Split into the header (everything before `jobs:`) and top-level jobs.
jobs_at = next(i for i, l in enumerate(lines) if l.rstrip() == "jobs:")
header, body = lines[: jobs_at + 1], lines[jobs_at + 1 :]
jobs: dict[str, list[str]] = {}
current = None
for line in body:
    m = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
    if m:
        current = m.group(1)
        jobs[current] = []
    if current:
        jobs[current].append(line)

KEEP = ["generate-bridge", "build-RustDeskTempTopMostWindow", "build-for-windows-flutter", "build-rustdesk-linux"]
missing = [k for k in KEEP if k not in jobs]
assert not missing, f"upstream jobs renamed: {missing}"


def drop_matrix_entry(job: str, marker: str) -> str:
    """Remove the `- { ... }` matrix entry containing `marker`."""
    return re.sub(r"\n\s*- \{[^{}]*" + re.escape(marker) + r"[^{}]*\}", "", job, count=1)


def must_replace(text: str, old: str, new: str) -> str:
    assert old in text, f"upstream step changed: {old[:60]!r}"
    return text.replace(old, new, 1)


windows = "".join(jobs["build-for-windows-flutter"])
windows = drop_matrix_entry(windows, "aarch64-pc-windows-msvc")
# The installer (and RustDesk's own install code) expects <app name>.exe.
windows = must_replace(
    windows,
    "mv ./flutter/build/windows/${{ matrix.job.flutter-arch }}/runner/Release ./rustdesk\n",
    "mv ./flutter/build/windows/${{ matrix.job.flutter-arch }}/runner/Release ./rustdesk\n"
    "          mv ./rustdesk/rustdesk.exe ./rustdesk/RemoteByiBoon.exe\n",
)
windows = must_replace(
    windows,
    "python3 ./generate.py -f ../../rustdesk/ -o . -e ../../rustdesk/rustdesk.exe",
    "python3 ./generate.py -f ../../rustdesk/ -o . -e ../../rustdesk/RemoteByiBoon.exe",
)
windows = must_replace(
    windows,
    "python preprocess.py --arp -d ../../rustdesk",
    'python preprocess.py --arp -d ../../rustdesk --app-name RemoteByiBoon --display-name "TeamViewer by iBoon" -m "iBoon Technologies" -v ${{ env.VERSION }}',
)
windows = windows.replace("rustdesk-${{ env.VERSION }}-${{ matrix.job.arch }}", "remote-by-iboon-${{ env.VERSION }}-${{ matrix.job.arch }}")
windows = windows.replace("./SignOutput/rustdesk-*.msi", "./SignOutput/remote-by-iboon-*.msi")
windows = windows.replace("./SignOutput/rustdesk-*.exe", "./SignOutput/remote-by-iboon-*.exe")
windows = windows.replace("../../SignOutput/rustdesk-*.msi", "../../SignOutput/remote-by-iboon-*.msi")

linux = "".join(jobs["build-rustdesk-linux"])
linux = drop_matrix_entry(linux, "aarch64-unknown-linux-gnu")

out = "".join(header).replace(
    "name: Build the flutter version of the RustDesk",
    "# GENERATED by res/iboon/make_workflow.py from flutter-build.yml -- edit that script.\n"
    "name: Build TeamViewer by iBoon (remote-by-iboon)",
)
# VERSION stays upstream's (1.4.9): Linux artifact names are built from it.
# Our own releases are told apart by their tag (iboon-1.4.9-1, ...).
out += "".join(jobs["generate-bridge"]) + "".join(jobs["build-RustDeskTempTopMostWindow"]) + windows + linux

(ROOT / ".github/workflows/iboon-build.yml").write_text(out, encoding="utf-8")
print("wrote .github/workflows/iboon-build.yml")
